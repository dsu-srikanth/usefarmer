import { useState } from "react";

function CropRecommendation() {

    const [soil, setSoil] = useState("");
    const [season, setSeason] = useState("");
    const [water, setWater] = useState("");
    const [land, setLand] = useState("");
    const [location, setLocation] = useState("");

    function submitRecommendation(e) {

        e.preventDefault();

        alert("🌱 Crop recommendation generated!");

        console.log("Soil:", soil);
        console.log("Season:", season);
        console.log("Water Requirement:", water);
        console.log("Land Area:", land);
        console.log("Location:", location);

        if (
            soil === "Black Soil" &&
            season === "Kharif" &&
            water === "Medium"
        ) {
            console.log("Recommended Crops:");
            console.log("🌽 Maize");
            console.log("🌿 Cotton");
            console.log("🫘 Soybean");
        } else {
            console.log(
                "Recommended crops will be generated by Python business logic."
            );
        }

        setSoil("");
        setSeason("");
        setWater("");
        setLand("");
        setLocation("");
    }

    return (

        <div className="crop-form">

            {/* Form Title */}

            <div className="form-title">

                <div className="form-title-icon">
                    🌱
                </div>

                <div>
                    <h2>Crop Recommendation</h2>

                    <p>
                        Enter farm details to get suitable crops
                    </p>
                </div>

            </div>


            <form onSubmit={submitRecommendation}>

                {/* Soil Type */}

                <div className="form-group">

                    <label>
                        🌍 Soil Type
                    </label>

                    <select
                        value={soil}
                        onChange={(e) => setSoil(e.target.value)}
                        required
                    >

                        <option value="">
                            Select soil type
                        </option>

                        <option value="Black Soil">
                            Black Soil
                        </option>

                        <option value="Red Soil">
                            Red Soil
                        </option>

                        <option value="Alluvial Soil">
                            Alluvial Soil
                        </option>

                        <option value="Clay Soil">
                            Clay Soil
                        </option>

                        <option value="Sandy Soil">
                            Sandy Soil
                        </option>

                    </select>

                </div>


                {/* Season */}

                <div className="form-group">

                    <label>
                        ☀️ Season
                    </label>

                    <select
                        value={season}
                        onChange={(e) => setSeason(e.target.value)}
                        required
                    >

                        <option value="">
                            Select season
                        </option>

                        <option value="Kharif">
                            Kharif
                        </option>

                        <option value="Rabi">
                            Rabi
                        </option>

                        <option value="Zaid">
                            Zaid
                        </option>

                    </select>

                </div>


                {/* Water */}

                <div className="form-group">

                    <label>
                        💧 Water Availability
                    </label>

                    <select
                        value={water}
                        onChange={(e) => setWater(e.target.value)}
                        required
                    >

                        <option value="">
                            Select water availability
                        </option>

                        <option value="Low">
                            Low
                        </option>

                        <option value="Medium">
                            Medium
                        </option>

                        <option value="High">
                            High
                        </option>

                    </select>

                </div>


                {/* Land Area */}

                <div className="form-group">

                    <label>
                        🌾 Land Area
                    </label>

                    <input
                        type="number"
                        placeholder="Enter land area in acres"
                        value={land}
                        onChange={(e) => setLand(e.target.value)}
                        min="0"
                        step="0.01"
                        required
                    />

                </div>


                {/* Location */}

                <div className="form-group">

                    <label>
                        📍 Location
                    </label>

                    <input
                        type="text"
                        placeholder="Enter farmer location"
                        value={location}
                        onChange={(e) => setLocation(e.target.value)}
                        required
                    />

                </div>


                {/* Submit */}

                <button
                    type="submit"
                    className="add-crop-button"
                >
                    🌱 Get Crop Recommendation
                </button>

            </form>

        </div>
    );
}

export default CropRecommendation;